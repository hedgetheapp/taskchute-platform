import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Temporal } from "@js-temporal/polyfill";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const snapshotPath = join(scriptDir, "../src/shared/japanese-holidays.ts");
const sourcePageUrl = "https://www8.cao.go.jp/chosei/shukujitsu/gaiyou.html";
const sourceCsvUrl = "https://www8.cao.go.jp/chosei/shukujitsu/syukujitsu.csv";

function fail(message) {
  throw new Error(`Japanese holiday snapshot update failed: ${message}`);
}

function parseDate(value, rowNumber) {
  if (!/^\d{4}\/\d{1,2}\/\d{1,2}$/.test(value)) fail(`row ${rowNumber} has an invalid date`);
  const [year, month, day] = value.split("/").map(Number);
  let date;
  try {
    date = Temporal.PlainDate.from({ year, month, day });
  } catch {
    fail(`row ${rowNumber} has an impossible Gregorian date`);
  }
  return date.toString();
}

function parseCsv(text) {
  const lines = text.replace(/^\uFEFF/, "").split(/\r?\n/);
  while (lines.at(-1) === "") lines.pop();
  if (lines.length < 2) fail("the CSV is empty or has no data rows");
  if (lines[0] !== "国民の祝日・休日月日,国民の祝日・休日名称") fail("unexpected CSV header");
  const rows = [];
  const seen = new Set();
  for (let index = 1; index < lines.length; index += 1) {
    const rowNumber = index + 1;
    const line = lines[index];
    const comma = line.indexOf(",");
    if (comma <= 0 || comma !== line.lastIndexOf(",")) fail(`row ${rowNumber} is malformed`);
    const logicalDate = parseDate(line.slice(0, comma), rowNumber);
    const label = line.slice(comma + 1).trim();
    if (!label) fail(`row ${rowNumber} has an empty label`);
    if (seen.has(logicalDate)) fail(`duplicate date ${logicalDate}`);
    seen.add(logicalDate);
    rows.push({ logical_date: logicalDate, label });
  }
  if (rows.length === 0) fail("the dataset has no rows");
  rows.sort((left, right) => left.logical_date.localeCompare(right.logical_date));
  for (let index = 1; index < rows.length; index += 1) {
    if (rows[index - 1].logical_date >= rows[index].logical_date) fail("dates are not strictly ordered");
  }
  const firstYear = Number(rows[0].logical_date.slice(0, 4));
  const lastYear = Number(rows.at(-1).logical_date.slice(0, 4));
  if (firstYear < 1955 || lastYear < firstYear) fail("unexpected coverage years");
  return { rows, coverage_start: `${firstYear}-01-01`, coverage_end: `${lastYear}-12-31` };
}

const response = await fetch(sourceCsvUrl);
if (!response.ok) fail(`HTTP ${response.status}`);
const bytes = Buffer.from(await response.arrayBuffer());
const sourceSha256 = createHash("sha256").update(bytes).digest("hex");
let decoded;
try {
  decoded = new TextDecoder("shift_jis", { fatal: true }).decode(bytes);
} catch {
  fail("CSV could not be decoded as Shift_JIS");
}
const parsed = parseCsv(decoded);

try {
  const existing = await readFile(snapshotPath, "utf8");
  const existingStart = existing.match(/coverage_start: "(\d{4}-\d{2}-\d{2})"/)?.[1];
  const existingEnd = existing.match(/coverage_end: "(\d{4}-\d{2}-\d{2})"/)?.[1];
  if (existingStart && parsed.coverage_start > existingStart) fail("coverage start regressed");
  if (existingEnd && parsed.coverage_end < existingEnd) fail("coverage end regressed");
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}

const entries = parsed.rows.map((row) => `  { logical_date: ${JSON.stringify(row.logical_date)}, label: ${JSON.stringify(row.label)} },`).join("\n");
const output = `// Generated by scripts/update-jp-holidays.mjs. Do not edit manually.\n// Source: ${sourcePageUrl}\n// CSV: ${sourceCsvUrl}\n\nexport interface JapaneseHolidayEntry {\n  logical_date: string;\n  label: string;\n}\n\nexport const JAPANESE_HOLIDAY_SOURCE = {\n  page_url: ${JSON.stringify(sourcePageUrl)},\n  csv_url: ${JSON.stringify(sourceCsvUrl)},\n  coverage_start: ${JSON.stringify(parsed.coverage_start)},\n  coverage_end: ${JSON.stringify(parsed.coverage_end)},\n  source_sha256: ${JSON.stringify(sourceSha256)},\n} as const;\n\nexport const JAPANESE_HOLIDAYS: readonly JapaneseHolidayEntry[] = [\n${entries}\n];\n\nexport function findJapaneseHoliday(logicalDate: string): JapaneseHolidayEntry | null {\n  let low = 0;\n  let high = JAPANESE_HOLIDAYS.length - 1;\n  while (low <= high) {\n    const middle = Math.floor((low + high) / 2);\n    const candidate = JAPANESE_HOLIDAYS[middle];\n    if (candidate.logical_date === logicalDate) return candidate;\n    if (candidate.logical_date < logicalDate) low = middle + 1;\n    else high = middle - 1;\n  }\n  return null;\n}\n`;
await writeFile(snapshotPath, output, "utf8");
console.log(JSON.stringify({ snapshot: snapshotPath, entries: parsed.rows.length, coverage_start: parsed.coverage_start, coverage_end: parsed.coverage_end, source_sha256: sourceSha256 }));
